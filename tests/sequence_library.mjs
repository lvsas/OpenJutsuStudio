import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const text=await readFile(new URL('../src/static/sequence-library.js',import.meta.url),'utf8');
const {mergeSequenceLibrary}=await import('data:text/javascript;base64,'+Buffer.from(text).toString('base64'));
const id=n=>n.toString(16).padStart(32,'0');
const native=(n,job)=>({take:{take_id:id(n),origin:{source_job:job||'remote-job'}},media_url:`/api/continuity/takes/${id(n)}/media`,capsule_url:`/api/continuity/takes/${id(n)}/capsule`});
const job=(n,engine='minimax-h3',extra={})=>({job_id:id(n),engine,status:'done',created:n,...extra});
const original=native(1), rows=[job(2),job(3,'ltx25-ripple'),job(4,'flux3-klein-character'),job(5,'minimax-h3',{status:'running'})];
let entries=mergeSequenceLibrary([original],rows);
assert.equal(entries.length,3);
assert.equal(entries[0].take.take_id,id(1));
assert.deepEqual(entries.slice(1).map(e=>e.job.engine),['minimax-h3','ltx25-ripple']);
assert.equal(entries[1].media_url,`/api/jobs/${id(2)}/result`);
assert.equal(entries[1].kind,'swap');assert.equal(entries[1].take,undefined);
assert.equal(original.project_job_ids,undefined);
entries=mergeSequenceLibrary([original],[job(8,'minimax-h3',{native_take_id:id(1)})]);
assert.equal(entries.length,1);assert.deepEqual(entries[0].project_job_ids,[id(8)]);
assert.equal(original.project_job_ids,undefined);
entries=mergeSequenceLibrary([native(1,id(9)),native(2,id(9))],[job(9)]);
assert.equal(entries.length,2);assert.deepEqual(entries.map(e=>e.project_job_ids),[[id(9)],[id(9)]]);
entries=mergeSequenceLibrary([native(1,id(9))],[job(9,'minimax-h3',{native_take_id:id(1),native_artifact_relation:'native-raw-family-and-distinct-finished-swap'})]);
assert.equal(entries.length,2,'Distinct sampled state must not replace the finished Swap');
assert.equal(entries[1].kind,'swap');
assert.equal(entries[1].job.native_artifact_relation,'native-raw-family-and-distinct-finished-swap');
entries=mergeSequenceLibrary([native(1)],[job(1)]);
assert.equal(entries.length,2,'UUID collision is not proof of native linkage');
entries=mergeSequenceLibrary([],[job(1),job(1),job(2,'minimax-h3',{native_take_id:id(99)}),job(3,'minimax-h3',{job_id:'../unsafe'}),job(4,'minimax-h3',{private_prompt:'must not cross',result:'/private/path'})]);
assert.equal(entries.length,3);
assert.equal(entries[1].kind,'swap','Unregistered native linkage stays video-only');
assert.equal(JSON.stringify(entries).includes('private'),false);
assert.throws(()=>mergeSequenceLibrary({},[]));assert.throws(()=>mergeSequenceLibrary([],{}));
console.log('Sequence library: native/Swap discovery, dedup, linkage, both engines, privacy and collision contracts passed');
