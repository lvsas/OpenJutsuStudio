"""The competition's written requirements, enforced as tests.

These are not style rules. A submission without an open-source licence, without setup
detail, or carrying private network addresses is a rejected submission, and a workflow file
that drifts from the code that runs is a false claim in the repository.

Requirement list, from the competition page:
  - built with ComfyUI; entirely local, Cloud, Developer Platform, Router, SDK or a mix
  - the repo includes an open-source licence and enough setup detail to run it elsewhere
  - other tools, models or techniques are allowed and must be explained in the demo video
  - lawful, SFW, no unlicensed IP or likenesses
  - one submission per person
"""
import json
import re
import sys
import unittest
from pathlib import Path
from release_inventory import release_files, release_paths

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

PRIVATE_ADDRESS = re.compile(
    r'\b(?:10\.\d{1,3}\.\d{1,3}\.\d{1,3}'
    r'|192\.168\.\d{1,3}\.\d{1,3}'
    r'|172\.(?:1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3})\b')
SKIP_PARTS = {'.git', '.venv', 'work', '__pycache__', 'node_modules', 'cache'}
SHIPPED_SUFFIXES = {'.py', '.js', '.mjs', '.css', '.html', '.md', '.sh', '.json', '.yaml', '.yml'}
WORKFLOW_FILES = {
    'ltx-frame-edit.api.json': 'build_frame_edit',
    'ltx-ripple.api.json': 'build_ripple',
    'h3-recast.api.json': 'build_h3_recast',
    # Vendor topology, not generated by us. Its adapter has a separate contract test.
    'flux3-klein-official-t2i.json': None,
}


def shipped_files():
    yield from release_files(ROOT)


class CompetitionRequirementsTests(unittest.TestCase):
    def test_no_private_network_address_is_committed(self):
        offenders = []
        for path in shipped_files():
            try:
                text = path.read_text()
            except (UnicodeDecodeError, OSError):
                continue
            if PRIVATE_ADDRESS.search(text):
                offenders.append(str(path.relative_to(ROOT)))
        self.assertEqual(offenders, [], f'Private addresses must not ship: {offenders}')

    def test_only_public_documentation_is_tracked(self):
        public = {'docs/README.md', 'docs/local-setup.md', 'docs/executor-setup.md',
                  'docs/dependencies.md', 'docs/model-licences.md',
                  'docs/readme/h3-studio-current.png', 'docs/readme/demo.gif',
                  'docs/audit-allowlist.txt'}
        tracked = [str(path.relative_to(ROOT)) for path in release_paths(ROOT)
                   if path.relative_to(ROOT).parts[0] == 'docs']
        self.assertEqual(sorted(set(tracked) - public - {''}), [],
                         'Remove private documentation from the index, not from disk')

    def test_public_docs_allowlist_and_private_artifacts_ignore_rules(self):
        import subprocess
        ignored = ['docs/plans/new.md', 'docs/validation/local.md', 'docs/audits/local.md',
                   'docs/architecture/local.md', 'docs/jury-guide.md', 'docs/local-notes.md',
                   'docs/readme/unapproved.png', 'src/static/jury-v2-review/index.html',
                   'artifacts/report.md', 'reports/probe.json', 'bundle.zip', 'bundle.tar.gz']
        public = ['docs/README.md', 'docs/local-setup.md', 'docs/executor-setup.md',
                  'docs/dependencies.md', 'docs/model-licences.md',
                  'docs/readme/h3-studio-current.png', 'dist/opengenjutsu-continuity.zip']
        import tempfile
        with tempfile.TemporaryDirectory() as folder:
            fixture = Path(folder)
            subprocess.run(['git', 'init', '-q', str(fixture)], check=True, capture_output=True)
            (fixture / '.gitignore').write_bytes((ROOT / '.gitignore').read_bytes())
            for target in ignored + public:
                with self.subTest(target=target):
                    result = subprocess.run(['git', '-c', 'core.excludesFile=/dev/null',
                        'check-ignore', '--no-index', '-q', target],
                        cwd=fixture, capture_output=True)
                    self.assertEqual(result.returncode, 0 if target in ignored else 1)

    def test_current_contest_rules_do_not_require_managed_cloud(self):
        readme = (ROOT / 'README.md').read_text()
        self.assertIn('Entirely local execution is allowed', readme)
        self.assertIn('A deployed try-it link is optional', readme)
        self.assertIn('novel custom node packs', readme)
        self.assertIn('https://comfy.org/open-source-higgsfield', readme)

    def test_an_open_source_licence_ships_with_the_repository(self):
        licence = ROOT / 'LICENSE'
        self.assertTrue(licence.is_file(), 'the repository must carry a licence file')
        self.assertIn('Apache License', licence.read_text())

    def test_readme_keeps_its_licence_setup_and_workflow_pointers(self):
        readme = (ROOT / 'README.md').read_text()
        for pointer in ('Apache-2.0', 'LICENSE', 'docs/local-setup.md', 'workflows/'):
            with self.subTest(pointer=pointer):
                self.assertIn(pointer, readme)
        # The requirements say combined techniques must be explained in the demo video.
        self.assertIn('SDK', readme)

    def test_project_keeps_its_chosen_official_sdk_transport(self):
        transport = (ROOT / 'src' / 'comfy_transport.py').read_text()
        self.assertIn('from comfy_sdk import Comfy', transport)

    def test_workflow_files_ship_and_parse(self):
        manifest = (ROOT / 'workflows' / 'README.md').read_text()
        for name in WORKFLOW_FILES:
            with self.subTest(name=name):
                graph = json.loads((ROOT / 'workflows' / name).read_text())
                self.assertTrue(graph, 'a shipped workflow must not be empty')
                for node_id, node in graph.items():
                    self.assertIn('class_type', node, f'{name} node {node_id}')
                    self.assertIn('inputs', node, f'{name} node {node_id}')
                self.assertIn(name, manifest, 'every shipped workflow needs a reader-facing manifest entry')

    def test_exported_workflows_do_not_drift_from_their_builders(self):
        """A shipped workflow that no longer matches the code is a false claim."""
        from graphs import build_frame_edit, build_ripple
        from h3_recipe import bind_frames, make_recipe
        expected = {
            'ltx-frame-edit.api.json': build_frame_edit(
                'og-source-frame-placeholder.png',
                'Replace the main performer with the character shown in the reference image.',
                reference_image='og-character-reference-placeholder.png'),
            'ltx-ripple.api.json': build_ripple(
                'og-source-video-placeholder.mp4', 'og-edited-frame-placeholder.png'),
            'h3-recast.api.json': bind_frames(
                make_recipe(source_width=1920, source_height=1080), 56,
                source_audio=True)['graph_template'],
        }
        for name, graph in expected.items():
            with self.subTest(name=name):
                self.assertEqual(json.loads((ROOT / 'workflows' / name).read_text()), graph)

    def test_readme_images_exist_and_are_tracked(self):
        """A README that points at an untracked image shows a broken repository."""
        distributed = set(release_paths(ROOT))
        readme = (ROOT / 'README.md').read_text()
        referenced = re.findall(r'!\[[^\]]*\]\(([^)]+)\)', readme)
        self.assertTrue(referenced, 'the README must show the running app')
        for target in referenced:
            if target.startswith(('http://', 'https://')):
                continue
            with self.subTest(target=target):
                self.assertTrue((ROOT / target).is_file(), f'{target} is referenced but missing')
                self.assertIn(ROOT / target, distributed,
                              f'{target} is referenced by the README but not distributed')

    def test_documentation_links_resolve_to_tracked_files(self):
        """A documentation index with dead links is worse than no index."""
        distributed = set(release_paths(ROOT))
        for name in ('README.md', 'docs/README.md'):
            page = ROOT / name
            self.assertTrue(page.is_file(), f'{name} must exist')
            for target in re.findall(r'\]\(([^)#]+)\)', page.read_text()):
                if target.startswith(('http://', 'https://', 'mailto:')):
                    continue
                with self.subTest(page=name, target=target):
                    resolved = (page.parent / target).resolve()
                    self.assertTrue(resolved.is_file(), f'{name} links to a missing file: {target}')
                    relative = str(resolved.relative_to(ROOT))
                    self.assertIn(resolved, distributed,
                                  f'{name} links to an undistributed file: {relative}')

    def test_no_local_paths_ship_in_the_workflows(self):
        for name in WORKFLOW_FILES:
            text = (ROOT / 'workflows' / name).read_text()
            with self.subTest(name=name):
                for leak in ('/home/', '/Users/', '127.0.0.1', 'localhost'):
                    self.assertNotIn(leak, text)


if __name__ == '__main__':
    unittest.main()
